export type Lang = keyof typeof translations;
export const defaultLang: Lang = 'en';
export const supportedLangs = Object.keys(translations) as Lang[];

export function t(lang: Lang, key: string): string {
  const keys = key.split('.');
  let obj: any = translations[lang] ?? translations[defaultLang];
  for (const k of keys) {
    obj = obj?.[k];
    if (obj === undefined) {
      // Fallback to English
      obj = translations[defaultLang];
      for (const fk of keys) obj = obj?.[fk];
      break;
    }
  }
  return typeof obj === 'string' ? obj : key;
}
